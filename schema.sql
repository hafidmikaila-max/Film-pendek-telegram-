create table if not exists public.films (
 id bigint generated by default as identity primary key,
 title text not null, category text not null, poster text not null,
 video_url text not null, description text default '', created_at timestamptz not null default now()
);
alter table public.films enable row level security;
drop policy if exists "Public read films" on public.films;
create policy "Public read films" on public.films for select to anon, authenticated using (true);
drop policy if exists "Logged in insert films" on public.films;
create policy "Logged in insert films" on public.films for insert to authenticated with check (auth.uid() is not null);
drop policy if exists "Logged in update films" on public.films;
create policy "Logged in update films" on public.films for update to authenticated using (auth.uid() is not null) with check (auth.uid() is not null);
drop policy if exists "Logged in delete films" on public.films;
create policy "Logged in delete films" on public.films for delete to authenticated using (auth.uid() is not null);
grant select on public.films to anon, authenticated;
grant insert, update, delete on public.films to authenticated;
grant usage, select on sequence public.films_id_seq to authenticated;
